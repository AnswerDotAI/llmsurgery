def _pb_ts(buf):
    "Decode a protobuf Timestamp message into an ISO-8601 UTC string"
    if not buf: return ''
    fs = _pb_decode(buf)
    sec, ns = _pb_one(fs, 1, 0), _pb_one(fs, 2, 0)
    dt = datetime.fromtimestamp(sec + ns/1e9, timezone.utc)
    return dt.isoformat(timespec='milliseconds').replace('+00:00', 'Z')

def _pb_ts_bytes(dt=None):
    "Encode a datetime (default: current UTC time) as a protobuf Timestamp"
    dt = dt or datetime.now(timezone.utc)
    sec = int(dt.timestamp())
    return _pb_f_int(1, sec) + _pb_f_int(2, dt.microsecond * 1000)

