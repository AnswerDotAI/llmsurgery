def _parse_call(buf):
    fs = _pb_decode(buf)
    raw_args = _pb_str(fs, 3)
    try: args = json.loads(raw_args) if raw_args else {}
    except ValueError: args = dict(raw=raw_args)
    name, args = _norm_call(_pb_str(fs, 2), args)
    return AttrDict(id=_pb_str(fs, 1), name=name, arguments=args)

def _parse_step(idx, step_type, status, meta_b, err_b, payload_b):
    pf = _pb_decode(payload_b)
    mf = _pb_decode(meta_b or _pb_one(pf, 5, b''))
    base = AttrDict(idx=idx, step_type=step_type, status=status, created=_pb_ts(_pb_one(mf, 1)), step_id=_pb_str(mf, 35))
    if step_type == STEP_USER:
        f19 = _pb_decode(_pb_one(pf, 19, b''))
        txt = _pb_str(f19, 2) or ''.join(_pb_str(_pb_decode(b), 1) for b in _pb_all(f19, 3))
        return AttrDict(**base, role='user', text=txt)
    if step_type == STEP_ASST:
        f20 = _pb_decode(_pb_one(pf, 20, b''))
        calls = [_parse_call(b) for b in _pb_all(f20, 7)]
        return AttrDict(**base, role='assistant', text=_pb_str(f20, 1), thinking=_pb_str(f20, 3), tool_calls=calls)
    if step_type == STEP_TOOL:
        cb = _pb_one(mf, 4)
        call = _parse_call(cb) if cb else AttrDict(id='', name='', arguments={})
        f140 = _pb_decode(_pb_one(pf, 140, b''))
        txt = _tool_result_text(f140, err_b, status)
        full = len(txt) > 2 and txt[0] == '𝍁' and txt[-1] == '𝍁'
        return AttrDict(**base, role='tool', call_id=call.id, tool_name=call.name, tool_args=call.arguments, text=txt, full=full)
