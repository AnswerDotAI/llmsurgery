def _trunc_sz(s, mx): return truncstr(s, mx, suf=f'…[{humanize(len(s))}]')

def _step_txt(s):
    if s.role == 'assistant':
        calls = [f"{c.name}({json.dumps(c.arguments)})" for c in s.get('tool_calls', ())]
        return '\n'.join(filter(None, [s.text, *calls]))
    return s.get('text', '')

class StepHits(L):
    "Search hits with one match-centered preview per line, each carrying its step on `.step`"
    steps = None
    def _new(self, items, *args, **kw):
        res = super()._new(items, *args, **kw)
        res.steps = self.steps
        return res
    def __repr__(self): return '\n'.join(f"{h.idx:5} {h.role:10} {h.preview}" for h in self)

def step_search(
    pat, # Regex to find
    steps, # Decoded steps, e.g. from `load_steps`
    maxlen=MAXLEN, # Preview characters around the match
):
    "Search decoded steps: `StepHits` rows, each carrying its step on `.step` and all searched steps on `.steps`"
    steps, res = L(steps), StepHits()
    for i, s in enumerate(steps):
        text = _step_txt(s)
        if m := re.search(pat, text):
            h = maxlen // 2
            a, b = max(0, m.start()-h), min(len(text), m.end()+h)
            prev = ('…' if a else '') + text[a:b].replace('\n', ' ') + ('…' if b < len(text) else '')
            if a or b < len(text): prev += f'[{humanize(len(text))}]'
            res.append(AttrDict(i=i, idx=s.idx, role=s.role, preview=prev, step=s))
    res.steps = steps
    return res

