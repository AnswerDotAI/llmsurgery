def _pb_varint(n):
    "Encode unsigned integer `n` as a protobuf base-128 varint"
    out = bytearray()
    while True:
        b = n & 0x7f
        n >>= 7
        if n: out.append(b | 0x80)
        else:
            out.append(b)
            return bytes(out)

def _pb_read_varint(buf, pos):
    res = shift = 0
    while True:
        b = buf[pos]
        pos += 1
        res |= (b & 0x7f) << shift
        if not (b & 0x80): return res, pos
        shift += 7

def _pb_decode(buf):
    "Decode protobuf wire bytes into `(field_num, wire_type, value)` tuples"
    pos, n, out = 0, len(buf), []
    while pos < n:
        tag, pos = _pb_read_varint(buf, pos)
        fn, wt = tag >> 3, tag & 7
        if wt == 0: v, pos = _pb_read_varint(buf, pos)
        elif wt == 1: v, pos = buf[pos:pos+8], pos+8
        elif wt == 2:
            ln, pos = _pb_read_varint(buf, pos)
            v, pos = buf[pos:pos+ln], pos+ln
        elif wt == 5: v, pos = buf[pos:pos+4], pos+4
        else: raise ValueError(f'Unknown protobuf wire type {wt} at offset {pos}')
        out.append((fn, wt, v))
    return out

def _pb_f_int(fn, v): return _pb_varint((fn << 3) | 0) + _pb_varint(v)
def _pb_f_bytes(fn, b):
    if isinstance(b, str): b = b.encode('utf-8')
    return _pb_varint((fn << 3) | 2) + _pb_varint(len(b)) + b

def _pb_one(fields, fn, default=None): return next((v for f,_,v in fields if f == fn), default)
def _pb_all(fields, fn): return [v for f,_,v in fields if f == fn]
def _pb_str(fields, fn, default=''):
    v = _pb_one(fields, fn)
    return v.decode('utf-8', 'replace') if isinstance(v, bytes) else default

