def prepare_compaction(
    ref=None, # Conversation id, prefix, or title; current or project's newest if None
    cwd='.', # Project directory
    agy_home=None, # Antigravity app data directory, list of directories, or None for CLI and desktop
    policy=compact_policy, # Token budget dictionary for `compact_chat`
    enc=None, # Tokenizer encoding; `compact_enc()` if None
):
    "Prepare an incremental synthetic compaction without writing to SQLite"
    cid, path = resolve_conv(ref, cwd, agy_home)
    steps = load_steps(path)
    with _ro_conn(path) as con:
        row = con.execute('SELECT trajectory_id FROM trajectory_meta LIMIT 1').fetchone()
        gen_count = con.execute('SELECT count(*) FROM gen_metadata').fetchone()[0]
    traj_id = row[0] if row else cid
    prior, new_steps = split_compaction(steps)
    msgs = steps2chat(new_steps, agent_results=True)
    if not msgs and not prior: raise ValueError(f'No steps to compact in {cid}')
    new_chat = compact_chat(msgs, enc=enc, last_n=5, **policy)
    new_full = compact_chat(msgs, enc=enc, **{k:10**9 for k in policy})
    chat, full = join_compacts(prior, new_chat), join_compacts(prior, new_full)
    content = compact_content(chat, transcript_path(cid, path))
    next_idx = (max(s.idx for s in steps) + 1) if steps else 0
    step = checkpoint_step(next_idx, content, traj_id, cid, gen_count)
    return AttrDict(cid=cid, path=path, step=step, prior=prior, new_chat=new_chat, chat=chat, full=full,
        content=content, pre_toks=len_toks(full, enc), post_toks=len_toks(content, enc))

def append_compaction(
    compaction, # Result of `prepare_compaction`
):
    "Insert a prepared `CHECKPOINT` row into the conversation database and update `conversation_summaries.db`"
    s = compaction.step
    sql = ('INSERT INTO steps (idx, step_type, status, has_subtrajectory, metadata, step_payload, step_format) '
        'VALUES (?, ?, ?, 0, ?, ?, 0)')
    with sqlite3.connect(compaction.path) as con: con.execute(sql, (s.idx, s.step_type, s.status, s.metadata, s.step_payload))
    sdb = Path(compaction.path).parents[1]/'conversation_summaries.db'
    if sdb.exists():
        now = datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S.%f+00:00')
        with sqlite3.connect(sdb) as con:
            con.execute('UPDATE conversation_summaries SET step_count=?, last_modified_time=? WHERE conversation_id=?',
                (s.idx + 1, now, compaction.cid))
    return compaction.path

def compact_session(
    ref=None, # Conversation id, prefix, or title; current or project's newest if None
    cwd='.', # Project directory
    agy_home=None, # Antigravity app data directory, list of directories, or None for CLI and desktop
    policy=compact_policy, # Token budget dictionary for `compact_chat`
    enc=None, # Tokenizer encoding; `compact_enc()` if None
):
    "Generate and append a synthetic `CHECKPOINT` compaction"
    compaction = prepare_compaction(ref, cwd, agy_home, policy, enc)
    append_compaction(compaction)
    return compaction
