def steps2chat(
    steps, # Decoded steps from `load_steps`
    agent_results=False, # Include subagent messages, task notifications, and plan handoffs as user turns?
):
    "Convert Antigravity steps into canonical `Msg` objects"
    msgs = []
    def add(m, s):
        m.meta = dict(created=s.created, uid=s.step_id)
        msgs.append(m)
    for s in steps:
        if s.step_type == STEP_USER:
            if s.text.strip() in ('', '/compact'): continue
            add(Msg('user', [Text(s.text)]), s)
        elif s.step_type == STEP_ASST:
            parts = ([Text(s.text)] if s.text else []) + [ToolUse(c.id, c.name, c.arguments) for c in s.tool_calls]
            if parts: add(Msg('assistant', parts), s)
        elif s.step_type == STEP_TOOL:
            add(Msg('tool', [ToolResult(id=s.call_id, name=s.tool_name, arguments=s.tool_args, text=s.text, full=s.full)]), s)
        elif s.step_type == STEP_SYS and _is_agent_sys(s):
            if agent_results: add(Msg('user', [Text(s.text)]), s)
            elif not msgs:
                body = s.text.split(' content=', 1)[1].strip() if s.text.startswith('[Message] ') and ' content=' in s.text else s.text
                if body: add(Msg('user', [Text(body)]), s)
    return msgs

